/* Capturas de sitios PUBLICADOS y demostraciones verificables.
   No genera imágenes ficticias: conserva el aspecto real de la URL.
   Si una URL falla, deja el arte editorial como fallback en la UI. */
import {chromium} from 'playwright';
import {mkdir,writeFile} from 'node:fs/promises';
const targets=[
  {id:'archivo',url:'https://deepanalytica.github.io/archivo-tienda/',type:'Tienda publicada'},
  {id:'visual-art-ai',url:'https://visualartai.cl/',type:'Sitio comercial publicado'},
  {id:'praxios-os',url:'https://deepanalytica.github.io/praxios/',type:'Dossier público, no aplicación operativa'},
  {id:'conv-os',url:'https://deepanalytica.github.io/conv-os/',type:'Demostración con datos ficticios'},
  {id:'radar-conv-os',url:'https://deepanalytica.github.io/conv-os/radar/',type:'Demo experimental'},
  {id:'sin-humo',url:'https://deepanalytica.github.io/archivo-tienda/portafolio/proyectos/sin-humo/',type:'Lector de obra'},
  {id:'wal',url:'https://wal.cl/',type:'Sitio comercial'},
  {id:'inverse-reality-lab',url:'https://deepanalytica.github.io/inverse-reality-lab/lab.html',type:'Laboratorio de investigación'},
  {id:'el-puente',url:'https://deepanalytica.github.io/inverse-reality-lab/el-puente/',type:'Publicación navegable'}
];
await mkdir('assets/proof',{recursive:true});
await mkdir('artifacts',{recursive:true});
const results=[];
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
try{
  for(const t of targets){
    const page=await browser.newPage({viewport:{width:1280,height:800},deviceScaleFactor:1,reducedMotion:'reduce'});
    const record={id:t.id,url:t.url,kind:t.type,status:'unavailable'};
    try{
      const response=await page.goto(t.url,{waitUntil:'domcontentloaded',timeout:18000});
      record.http=response?.status()||0;
      record.finalUrl=page.url();
      const expectedHost=new URL(t.url).hostname.replace(/^www\./,'');
      const actualHost=new URL(record.finalUrl).hostname.replace(/^www\./,'');
      if(actualHost!==expectedHost)throw Error('Redirect to unexpected host');
      if(!record.http||record.http>=400)throw Error('HTTP '+record.http);
      await page.waitForTimeout(1300);
      await page.evaluate(()=>document.fonts?.ready).catch(()=>{});
      const details=await page.evaluate(()=>({title:document.title,bodyLength:document.body?.innerText?.trim().length||0,hasVisibleContent:!!document.querySelector('main,h1,[role="main"],.app,#app')}));
      record.title=details.title;record.bodyLength=details.bodyLength;
      if(details.bodyLength<65||!/./.test(details.title||''))throw Error('Insufficient public page content');
      if(/^(404|not found|página no encontrada|access denied)/i.test(details.title.trim()))throw Error('Unexpected error page');
      // Captura del navegador, no simulación ni archivo generado por IA.
      const out='assets/proof/'+t.id+'.jpg';
      await page.screenshot({path:out,type:'jpeg',quality:76,fullPage:false,animations:'disabled',timeout:12000});
      record.file=out;record.status='captured';
      console.log('CAPTURED '+t.id+' HTTP '+record.http+' '+out+' '+details.title.slice(0,85));
    }catch(e){record.error=String(e.message||e).slice(0,180);console.log('FALLBACK '+t.id+' '+record.error)}
    finally{await page.close()}
    results.push(record);
  }
}finally{await browser.close()}
const report={generatedAt:new Date().toISOString(),source:'Live public website screenshots generated by Playwright',results};
await writeFile('assets/proof/manifest.json',JSON.stringify(report,null,2));
await writeFile('artifacts/public-evidence-report.json',JSON.stringify(report,null,2));
const successes=results.filter(r=>r.status==='captured').length;
console.log('PUBLIC_EVIDENCE '+successes+'/'+targets.length+' successful; uncaptured projects retain clearly labelled editorial fallback');
